// Copies the shared protocol from the backend repo (source of truth).
// Usage: node scripts/sync-protocol.mjs [--check] [path-to-backend]
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const backend = resolve(args.find((a) => !a.startsWith('--')) ?? process.env.SKETCHSYNC_BACKEND ?? join(root, '..', 'sketchsync-Backend'));
const from = join(backend, 'src', 'shared');
const to = join(root, 'src', 'shared');

if (!existsSync(from)) {
    console.error(`Backend shared folder not found at ${from}. Pass the backend path as an argument.`);
    process.exit(check ? 1 : 2);
}

const header = '// GENERATED by scripts/sync-protocol.mjs from sketchsync-Backend/src/shared. Do not edit here.\n';
mkdirSync(to, { recursive: true });
let stale = [];
for (const file of readdirSync(from).filter((f) => f.endsWith('.ts'))) {
    const content = header + readFileSync(join(from, file), 'utf8');
    const target = join(to, file);
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (current === content) continue;
    if (check) stale.push(file);
    else writeFileSync(target, content);
}
for (const file of readdirSync(to).filter((f) => f.endsWith('.ts'))) {
    if (!existsSync(join(from, file))) stale.push(`${file} (not in backend)`);
}
if (check && stale.length) {
    console.error(`src/shared is out of date: ${stale.join(', ')}. Run: npm run sync-protocol`);
    process.exit(1);
}
console.log(check ? 'Protocol is in sync.' : `Synced protocol from ${from}`);
